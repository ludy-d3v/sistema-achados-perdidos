    private void jBcadastrarUsuarioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBcadastrarUsuarioActionPerformed
    // TODO add your handling code here:
        
    //pega os dados dos campos
    String nome = jTnome_usuario.getText().trim();
    String usuario = jTLogin.getText().trim();
    String senha = jTSenha.getText();
    String cpf = jTcpf.getText().trim();

    // Validação inicial do CPF(se tem só numero, e a quantidade de digitos necessária)
    if (!cpf.matches("\\d{11}")) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "O CPF deve conter somente 11 números.",
                "CPF inválido",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );

        return;
    }

    // Envia os dados para o Controller
    controller.setNome(nome);
    controller.setUsuario(usuario);
    controller.setSenha(senha);
    controller.setCPF(cpf);

    try {

        // Tenta cadastrar o usuário
        if (controller.cadastrarUsuario()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Usuário cadastrado com sucesso!",
                    "Sucesso",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

            // Abre a tela de login
            LoginView tela = new LoginView();
            tela.setLocationRelativeTo(this);
            tela.setVisible(true);

            // Fecha a tela de cadastro
            this.dispose();

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Não foi possível cadastrar o usuário!" + "Verifique se você já possui cadastro.",
                    "Erro",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }

    } catch (IllegalArgumentException e) {

        // Erros de validação do Controller
        javax.swing.JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Erro de validação",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );

    } catch (java.sql.SQLException e) {

        // Erros relacionados ao banco de dados
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao cadastrar usuário: "
                + e.getMessage(),
                "Erro",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_jBcadastrarUsuarioActionPerformed

