public void preencherRelatorio(
        int total,
        java.util.Map<String, Integer> categorias,
        java.util.Map<String, Integer> campus,
        java.util.Map<String, Integer> meses) {

    jLabelTotal.setText("TOTAL DE OBJETOS: " + total);

    jLabelCategoria.setText(
            montarTexto("OBJETOS POR CATEGORIA", categorias)
    );

    jLabelCampus.setText(
            montarTexto("OBJETOS POR CAMPUS", campus)
    );

    jLabelMes.setText(
            montarTexto("OBJETOS POR MÊS", meses)
    );
}

private String montarTexto(
        String titulo,
        java.util.Map<String, Integer> dados) {

    StringBuilder texto = new StringBuilder("<html>");
    texto.append(titulo).append("<br>");

    for (java.util.Map.Entry<String, Integer> item : dados.entrySet()) {
        texto.append(item.getKey())
             .append(": ")
             .append(item.getValue())
             .append("<br>");
    }

    texto.append("</html>");
    return texto.toString();
}
