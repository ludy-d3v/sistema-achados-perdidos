private void configurarBarra(javax.swing.JProgressBar barra) {
    barra.setUI(new javax.swing.plaf.basic.BasicProgressBarUI() {
        @Override
        protected void paintString(java.awt.Graphics g, int x, int y,
                int width, int height, int amountFull, java.awt.Insets b) {

            g.setColor(java.awt.Color.BLACK);
            super.paintString(g, x, y, width, height, amountFull, b);
        }
    });

    barra.setForeground(new java.awt.Color(0, 120, 215));
    barra.setBackground(java.awt.Color.WHITE);
    barra.setStringPainted(true);
}
    
private void configurarPercentual(
        javax.swing.JProgressBar barra,
        java.util.Map<String, Integer> dados,
        int total) {

    int maiorQuantidade = 0;

    for (int valor : dados.values()) {
        if (valor > maiorQuantidade) {
            maiorQuantidade = valor;
        }
    }

    int porcentagem = total > 0
            ? (int) Math.round((maiorQuantidade * 100.0) / total)
            : 0;

    barra.setMinimum(0);
    barra.setMaximum(100);
    barra.setValue(porcentagem);
    barra.setString(porcentagem + "%");
}
    
public void preencherRelatorio(
        int total,
        java.util.Map<String, Integer> categorias,
        java.util.Map<String, Integer> campus,
        java.util.Map<String, Integer> meses) {

    jLabelTotal.setText("TOTAL DE OBJETOS CADASTRADOS: " + total);

    jLabelCategoria.setText(montarTexto("OBJETOS POR CATEGORIA", categorias));
    jLabelCampus.setText(montarTexto("OBJETOS POR CAMPUS", campus));
    jLabelMes.setText(montarTexto("OBJETOS POR MÊS", meses));

    configurarPercentual(jProgressCategoria, categorias, total);
    configurarPercentual(jProgressCampus, campus, total);
    configurarPercentual(jProgressMes, meses, total);
}

private String montarTexto(
        String titulo,
        java.util.Map<String, Integer> dados) {

    StringBuilder texto = new StringBuilder("<html>");
    texto.append(titulo).append("<br>");

    for (java.util.Map.Entry<String, Integer> item : dados.entrySet()) {
        texto.append(item.getKey())
             .append(": ")
             .append(item.getValue())
             .append("<br>");
    }

    texto.append("</html>");
    return texto.toString();
}
